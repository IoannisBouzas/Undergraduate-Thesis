"""Exploratory token-proxy and phone-energy routing sensitivity.

The budget-aware memory literature often uses query tokens, compute or latency as a
cost proxy. This script checks whether a query-token proxy and a phone-energy model
select the same memory strategy. Raw-cost and quality-normalized comparisons are
reported separately.

The analysis is exploratory. Graph construction uses the direct S23 pilot, but graph
query energy is token-scaled from Vector RAG because no complete phone graph-QA run
exists. Accuracy and prompt tokens come from the workstation record. The resulting
grid belongs in the appendix and must not be described as a deployed phone router.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

from energy import amortization_frontier as af


RECORD = {
    "e2b": {
        "fullcontext": "lap_locomo200_e2b_fullcontext",
        "vectorrag": "lap_locomo200_e2b_vr_prefix",
        "graph_v3": "lap_locomo200_e2b_graphrag_v3_prefix",
    },
    "e4b": {
        "fullcontext": "lap_locomo200_e4b_fullcontext",
        "vectorrag": "lap_locomo200_e4b_vr_prefix",
        "graph_v3": "lap_locomo200_e4b_graphrag_v3_prefix",
    },
}
MODES = ("fullcontext", "vectorrag", "graph_v3")
LABEL = {"fullcontext": "fc", "vectorrag": "vr", "graph_v3": "graph"}


def load_record() -> dict[str, dict[str, dict[str, float]]]:
    with Path("results/master_table.csv").open(encoding="utf-8") as handle:
        rows = {row["dir"]: row for row in csv.DictReader(handle)}
    return {
        model: {
            mode: {
                "acc": float(rows[run]["judge"]),
                "ptok": float(rows[run]["prompt_tok"]),
            }
            for mode, run in runs.items()
        }
        for model, runs in RECORD.items()
    }


def energy_total_j(model: str, mode: str, history_turns: int, queries: int) -> float:
    return af.E_ING[mode] * history_turns + queries * af.e_query(model, mode)


def energy_per_correct_kj(
    model: str,
    mode: str,
    accuracy: float,
    history_turns: int,
    queries: int,
) -> float:
    return energy_total_j(model, mode, history_turns, queries) / (queries * accuracy) / 1000.0


def argmin_mode(scores: dict[str, float]) -> str:
    return min(scores, key=scores.get)


def main() -> None:
    record = load_record()
    report: dict[str, object] = {"headline": {}, "grid": {}, "operation_energy": {}}
    lines: list[str] = []
    write = lines.append

    write("# Exploratory token-proxy and phone-energy routing sensitivity\n")
    write(
        "*Generated by `routing_divergence.py`. Construction energy is a direct S23 "
        "measurement. Graph query energy is projected, and accuracy and prompt tokens "
        "come from workstation cells.*\n"
    )

    graph_vector_ratio = af.E_ING["graph_v3"] / af.E_ING["vectorrag"]
    graph_1000_kj = af.E_ING["graph_v3"]
    vector_1000_kj = af.E_ING["vectorrag"]
    write("## 1. Construction work omitted by a query-token proxy\n")
    write(
        f"Measured construction energy is **{af.E_ING['graph_v3']:.2f} J/turn** for "
        f"the graph pilot and **{af.E_ING['vectorrag']:.2f} J/turn** for vector "
        f"ingestion, a **{graph_vector_ratio:.1f}x** ratio. Linear scaling of these "
        f"per-turn anchors to 1,000 turns gives {graph_1000_kj:.1f} kJ and "
        f"{vector_1000_kj:.1f} kJ respectively. This is a scenario projection, not a "
        "full-charge estimate.\n"
    )
    report["headline"] = {
        "graph_j_per_turn": af.E_ING["graph_v3"],
        "vector_j_per_turn": af.E_ING["vectorrag"],
        "construction_energy_ratio": graph_vector_ratio,
        "graph_1000turn_kj_projected": graph_1000_kj,
        "vector_1000turn_kj_projected": vector_1000_kj,
    }

    tokens_per_turn = 64.0
    embed_j_per_token = af.E_ING["vectorrag"] / tokens_per_turn
    extract_j_per_token = af.E_ING["graph_v3"] / tokens_per_turn
    prefill_j_per_token = (
        af.E_QUERY["e2b"]["fullcontext"] / record["e2b"]["fullcontext"]["ptok"]
    )
    write("## 2. Operation-specific illustration\n")
    write(
        f"Using approximately {tokens_per_turn:.0f} tokens per dialogue turn, the "
        f"effective rates are {embed_j_per_token:.3f} J/token for vector ingestion, "
        f"{prefill_j_per_token:.3f} J/token for full-context query service and "
        f"{extract_j_per_token:.3f} J/token for graph extraction. These are "
        "operation-specific ratios, not a universal token price.\n"
    )
    report["operation_energy"] = {
        "embed_j_per_token": embed_j_per_token,
        "prefill_j_per_token": prefill_j_per_token,
        "extract_j_per_token": extract_j_per_token,
    }

    history_lengths = (50, 100, 200, 500, 1000)
    query_counts = (1, 5, 20, 50)
    raw_total_disagree = 0
    quality_total_disagree = 0
    total_profiles = 0
    write("## 3. Routing sensitivity grid\n")
    write(
        "Raw query-token footprint is compared with raw lifecycle energy. Query tokens "
        "per correct answer are compared with lifecycle energy per correct answer. The "
        "token side omits construction in both cases. Each cell is `raw energy / "
        "quality-normalized energy`; `*` marks a disagreement with the corresponding "
        "token proxy.\n"
    )

    for model in ("e2b", "e4b"):
        accuracy = {mode: record[model][mode]["acc"] for mode in MODES}
        prompt_tokens = {mode: record[model][mode]["ptok"] for mode in MODES}
        raw_token_pick = argmin_mode(prompt_tokens)
        quality_token_pick = argmin_mode(
            {mode: prompt_tokens[mode] / accuracy[mode] for mode in MODES}
        )
        write(f"\n### {model.upper()}\n")
        write(
            f"Raw query-token pick: **{LABEL[raw_token_pick]}**. Tokens-per-correct "
            f"pick: **{LABEL[quality_token_pick]}**.\n"
        )
        write("\n| L\\Q | " + " | ".join(f"Q={count}" for count in query_counts) + " |")
        write("|" + "---|" * (len(query_counts) + 1))

        raw_disagree = 0
        quality_disagree = 0
        grid: dict[str, dict[str, object]] = {}
        for history_turns in history_lengths:
            cells = []
            for queries in query_counts:
                energy = {
                    mode: energy_total_j(model, mode, history_turns, queries)
                    for mode in MODES
                }
                energy_per_correct = {
                    mode: energy_per_correct_kj(
                        model, mode, accuracy[mode], history_turns, queries
                    )
                    for mode in MODES
                }
                raw_energy_pick = argmin_mode(energy)
                quality_energy_pick = argmin_mode(energy_per_correct)
                raw_mismatch = raw_energy_pick != raw_token_pick
                quality_mismatch = quality_energy_pick != quality_token_pick
                raw_disagree += int(raw_mismatch)
                quality_disagree += int(quality_mismatch)
                cells.append(
                    f"{LABEL[raw_energy_pick]}{'*' if raw_mismatch else ''}/"
                    f"{LABEL[quality_energy_pick]}{'*' if quality_mismatch else ''}"
                )
                grid[f"L{history_turns}_Q{queries}"] = {
                    "raw_energy_optimal": LABEL[raw_energy_pick],
                    "quality_energy_optimal": LABEL[quality_energy_pick],
                    "raw_disagrees_with_query_tokens": raw_mismatch,
                    "quality_disagrees_with_tokens_per_correct": quality_mismatch,
                }
            write(f"| {history_turns} | " + " | ".join(cells) + " |")

        profiles = len(history_lengths) * len(query_counts)
        write(
            f"\nRaw choices disagree in **{raw_disagree}/{profiles}** profiles. "
            f"Quality-normalized choices disagree in **{quality_disagree}/{profiles}**.\n"
        )
        raw_total_disagree += raw_disagree
        quality_total_disagree += quality_disagree
        total_profiles += profiles
        report["grid"][model] = {
            "raw_token_pick": LABEL[raw_token_pick],
            "quality_token_pick": LABEL[quality_token_pick],
            "raw_disagreements": raw_disagree,
            "quality_normalized_disagreements": quality_disagree,
            "n_profiles": profiles,
            "cells": grid,
        }

    write("## 4. Interpretation\n")
    write(
        f"Across both readers, raw choices disagree in **{raw_total_disagree}/"
        f"{total_profiles}** profiles and quality-normalized choices disagree in "
        f"**{quality_total_disagree}/{total_profiles}**. These are grid descriptions, "
        "not statistical tests. The result changes when accuracy normalization is "
        "introduced, so the former 40-of-40 headline is retired. The stable conclusion "
        "is narrower: query tokens omit memory-construction work.\n"
    )
    write(
        "*Caveat:* no complete phone graph-QA run exists. Keep this sensitivity in the "
        "appendix until graph query energy and accuracy are measured on the phone.\n"
    )
    report["summary"] = {
        "raw_disagreements": raw_total_disagree,
        "quality_normalized_disagreements": quality_total_disagree,
        "n_profiles": total_profiles,
        "status": "exploratory_appendix_only",
    }

    Path("results/routing_divergence.md").write_text("\n".join(lines), encoding="utf-8")
    Path("results/routing_divergence.json").write_text(
        json.dumps(report, indent=2), encoding="utf-8"
    )
    print("\n".join(lines))
    print("\nwrote results/routing_divergence.{md,json}")


if __name__ == "__main__":
    main()
